from langchain_community.document_loaders import DataFrameLoader
from langchain_community.embeddings import HuggingFaceEmbeddings
from langchain_community.vectorstores import Chroma

# 1. Construir el resumen de cada fila de forma dinámica.
#    En lugar de hardcodear columnas, tomamos todas las que
#    existen en el CSV. Cada fila queda como un párrafo del
#    estilo "columna: valor. columna: valor." que el modelo
#    puede leer y entender como lenguaje natural.
def fila_a_texto(row):
    partes = []
    for col in row.index:
        valor = row[col]
        if pd.notna(valor):
            partes.append(f"{col}: {valor}")
    return ". ".join(partes) + "."

df_limpio['resumen_fila'] = df_limpio.apply(fila_a_texto, axis=1)

# Verificar cómo quedó un ejemplo para asegurarnos que el texto
# tiene sentido antes de vectorizar todo el dataset.
print("Ejemplo de fila convertida a texto:")
print(df_limpio['resumen_fila'].iloc[0])

# 2. DataFrameLoader convierte cada fila del CSV en un
#    "Document" de LangChain. Le indicamos qué columna usar
#    como contenido principal (el resumen que acabamos de crear).
loader = DataFrameLoader(df_limpio, page_content_column='resumen_fila')
documentos = loader.load()
print(f"\nTotal de documentos indexados: {len(documentos)}")

# 3. Modelo de embeddings: convierte texto → vector numérico.
#    Usamos "all-MiniLM-L6-v2" porque es gratuito, liviano y
#    corre directo en la RAM de Colab (no necesita API key).
#    Cada fragmento de texto queda representado como un punto
#    en un espacio de 384 dimensiones.
