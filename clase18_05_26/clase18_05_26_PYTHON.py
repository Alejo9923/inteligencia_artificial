import re
import unicodedata

# Función auxiliar para limpiar texto a fondo (eliminar acentos y caracteres raros)
def limpiar_texto_avanzado(texto):
    if pd.isna(texto):
        return "unknown"

    # 1. Convertir a string y a minúsculas
    texto = str(texto).lower().strip()

    # 2. Eliminar acentos (Ej: 'camión' -> 'camion')
    texto = unicodedata.normalize('NFKD', texto).encode('ascii', 'ignore').decode('utf-8')

    # 3. Reemplazar espacios y guiones intermedios por un único guión bajo
    texto = re.sub(r'[\s\-]+', '_', texto)

    # 4. Eliminar cualquier carácter que no sea una letra, número o guión bajo
    texto = re.sub(r'[^a-z0-9_]', '', texto)

    return texto

