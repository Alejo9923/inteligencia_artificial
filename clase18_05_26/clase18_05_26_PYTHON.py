# BLOQUE 5 — Construir la cadena RAG (versión moderna)
# LangChain eliminó RetrievalQA en versiones recientes y ahora
# recomienda construir la cadena manualmente usando LCEL
# (LangChain Expression Language), que encadena pasos con el
# operador | (pipe). El flujo es el mismo de antes:
#   pregunta → retriever → prompt con contexto → Mistral → respuesta
# ============================================================

from langchain_core.prompts import PromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser

# El prompt es el mismo que antes: define el rol del bot y
# dónde se inyectan el contexto recuperado y la pregunta.
prompt_template = PromptTemplate.from_template("""Eres un analista experto en ventas. Tienes acceso a un corpus
de datos de ventas reales. Responde ÚNICAMENTE basándote en el contexto
proporcionado. Si la información no está en el contexto, di exactamente:
"No encontré esa información en los datos disponibles."

Responde siempre en español, de forma clara y concisa.

Contexto del corpus de ventas:
{context}

Pregunta del usuario:
{question}

Respuesta del analista:""")

# Función auxiliar que convierte la lista de documentos
# recuperados por el retriever en un solo bloque de texto
# para pasárselo al prompt como {context}.
def formatear_docs(docs):
    return "\n\n".join(doc.page_content for doc in docs)

# Cadena LCEL: cada | conecta un paso con el siguiente.
#   RunnablePassthrough() → deja pasar la pregunta sin cambios
#   retriever | formatear_docs → busca documentos y los une en texto
#   prompt_template → arma el prompt completo con contexto + pregunta
#   llm → Mistral genera la respuesta
#   StrOutputParser() → extrae solo el texto de la respuesta
cadena_rag = (
    {
        "context": retriever | formatear_docs,
        "question": RunnablePassthrough()
    }
    | prompt_template
    | llm
    | StrOutputParser()
)

print("✓ Cadena RAG construida correctamente.")
print("✓ Flujo: Pregunta → RAG (corpus) → Mistral → Respuesta")

