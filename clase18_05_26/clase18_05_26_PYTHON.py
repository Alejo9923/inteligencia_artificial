# 4. Chroma es nuestra base de datos vectorial (vive en RAM).
#    El retriever es el "buscador": dada una pregunta del usuario,
#    la convierte en vector y devuelve los k=5 documentos más
#    similares del corpus. k=5 da más contexto que k=3.
vector_db = Chroma.from_documents(documentos, embeddings_local)
retriever = vector_db.as_retriever(search_kwargs={"k": 5})

